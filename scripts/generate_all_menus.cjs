      sodiumMg = 5;
      gi = name.includes('แตงโม') || name.includes('ทุเรียน') || name.includes('ลำไย') || name.includes('ขนุน') ? 'high' : (name.includes('ฝรั่ง') || name.includes('แอปเปิล') || name.includes('แก้วมังกร') || name.includes('ชมพู่') || name.includes('ส้มโอ') ? 'low' : 'medium');
      diabetesSuitability = gi === 'high' ? 'caution' : 'good';
