// Helper to convert RawMenuItem to full DishPreset format
export function convertRawMenuToPreset(raw: RawMenuItem): DishPreset {
  const weight = raw.defaultWeightG || 100;
  const factor = weight / 100;
  
  const kcalPer100 = Math.round(raw.kcal / factor);
  const carbsPer100 = parseFloat((raw.carbsG / factor).toFixed(1));
  const sugarPer100 = parseFloat((raw.sugarG / factor).toFixed(1));
  const proteinPer100 = parseFloat((raw.proteinG / factor).toFixed(1));
  const fatPer100 = parseFloat((raw.fatG / factor).toFixed(1));
  const fiberPer100 = parseFloat((raw.fiberG / factor).toFixed(1));
  const sodiumPer100 = Math.round(raw.sodiumMg / factor);

  let mainCategory: 'carb' | 'protein' | 'vegetable' | 'fruit' = 'protein';
  if (raw.categoryType === 'fruit') {
    mainCategory = 'fruit';
  } else if (raw.categoryType === 'dessert' || raw.categoryType === 'beverage') {
    mainCategory = 'carb';
  } else if (raw.categoryType === 'snack') {
    mainCategory = raw.carbsG > 15 ? 'carb' : (raw.fatG > 10 ? 'carb' : 'protein');
  } else {
    // savory
    if (raw.name.includes('ผัก') || raw.name.includes('แกงเลียง') || raw.name.includes('ตำลึง')) {
      mainCategory = 'vegetable';
    } else if (raw.carbsG > 30 || raw.name.includes('เส้น') || raw.name.includes('ข้าว')) {
      mainCategory = 'carb';
    } else {
      mainCategory = 'protein';
    }
  }

  return {
    id: `dish_preset_${raw.id}`,
    name: raw.name,
    categoryType: raw.categoryType,
    categoryThai: raw.categoryThai,
    defaultTotalWeightG: raw.defaultWeightG,
    description: `${raw.servingDesc} — ≈ ${raw.kcal} kcal (คาร์บ ${raw.carbsG}g, น้ำตาล ${raw.sugarG}g, โปรตีน ${raw.proteinG}g)`,
    healthNote: raw.healthNote,
    diabetesSuitability: raw.diabetesSuitability,
    ingredients: [
      {
        id: `ing_${raw.id}_main`,
        name: raw.name,
        category: mainCategory,
        ratioPercent: 100,
        density: {
          kcalPer100g: kcalPer100,
          carbsPer100g: carbsPer100,
          sugarPer100g: sugarPer100,
          proteinPer100g: proteinPer100,
          fatPer100g: fatPer100,
          fiberPer100g: fiberPer100,
          sodiumPer100g: sodiumPer100,
          glycemicIndex: raw.gi,
        },
        gi: raw.gi,
        isSelected: true,
      },
    ],
  };
}
